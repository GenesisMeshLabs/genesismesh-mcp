"""Render actual registered coverage; no handwritten parity totals."""

import argparse
from pathlib import Path

from genesismesh_mcp.catalog import build_catalog
from genesismesh_mcp.server import build_resource_targets, build_tools
from genesismesh_mcp.settings import Settings

OUTPUT = Path(__file__).resolve().parents[1] / "docs/coverage.md"


def render():
    report = build_catalog(build_tools(Settings()), resources=build_resource_targets())
    summary = report["summary"]
    lines = ["# Core coverage", "", "Generated by `python scripts/render_coverage.py`. Do not edit counts by hand.", "",
        f"Core **1.8.1**. **{summary['registered_tools']} registered tools**; **{summary['accounted']} contract entries accounted for**.",
        "Registration is not behavioral proof. Resources and low-level support are not independent executable capabilities.", "",
        "## Measured scope", "", "| Surface | Total | Status counts |", "| --- | ---: | --- |"]
    for name, counts in summary["sections"].items():
        status = "; ".join(f"{key}: {value}" for key, value in counts.items() if key != "total")
        lines.append(f"| {name} | {counts['total']} | {status} |")
    lines += ["", "## Remaining gaps and composed operations", "",
        "These do not count as implemented end-to-end workflows. Every CLI leaf also has a dedicated reference resource.", "",
        "| Core surface | Status | Reason |", "| --- | --- | --- |"]
    for row in report["rows"]:
        if row["implementation_status"] in {"gap", "components_available"}:
            reason = row.get("reason", "See packaged coverage.json for mapping details.").replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{row['id']}` | {row['implementation_status']} | {reason} |")
    for section in ("http_routes", "cli_commands", "python", "signed_artifacts"):
        lines += ["", f"## {section}", "", "| Core surface | Status | MCP mapping | Test evidence |",
                  "| --- | --- | --- | --- |"]
        for row in report["rows"]:
            if row["section"] != section:
                continue
            mapped = ", ".join(f"`{name}`" for name in row["tools"] or row["resources"]) or "See boundary/reason in catalog"
            lines.append(f"| `{row['id']}` | {row['implementation_status']} | {mapped} | {row['verification_status']} |")
    lines += ["", "The complete machine-readable inventory, per-item reasons and exact test references are in "
              "`src/genesismesh_mcp/data/coverage.json` and the `genesis-mesh://coverage` resource.", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Coverage documentation differs from actual registrations")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(content, encoding="utf-8", newline="\n")
